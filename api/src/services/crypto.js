import crypto from 'crypto';
import { ENV } from '../config/env.js';

const ALGORITHM = 'aes-256-gcm';
const IV_LENGTH = 12; // 96 bits for GCM

// Derive 32-byte key from master key
function getDerivedKey() {
  return crypto.createHash('sha256').update(ENV.FLE_MASTER_KEY).digest();
}

/**
 * Encrypt plaintext using AES-256-GCM
 * Output format: "enc:iv:authTag:ciphertext" (Hex encoded)
 */
export function encryptField(plainText) {
  if (plainText === null || plainText === undefined || plainText === '') {
    return plainText;
  }

  const textToEncrypt = typeof plainText === 'object' ? JSON.stringify(plainText) : String(plainText);
  const iv = crypto.randomBytes(IV_LENGTH);
  const key = getDerivedKey();

  const cipher = crypto.createCipheriv(ALGORITHM, key, iv);
  let encrypted = cipher.update(textToEncrypt, 'utf8', 'hex');
  encrypted += cipher.final('hex');

  const authTag = cipher.getAuthTag();

  return `enc:${iv.toString('hex')}:${authTag.toString('hex')}:${encrypted}`;
}

/**
 * Decrypt ciphertext generated by encryptField
 */
export function decryptField(cipherText, isObject = false) {
  if (!cipherText || typeof cipherText !== 'string' || !cipherText.startsWith('enc:')) {
    return cipherText;
  }

  try {
    const parts = cipherText.split(':');
    if (parts.length !== 4) return cipherText;

    const iv = Buffer.from(parts[1], 'hex');
    const authTag = Buffer.from(parts[2], 'hex');
    const encryptedText = parts[3];
    const key = getDerivedKey();

    const decipher = crypto.createDecipheriv(ALGORITHM, key, iv);
    decipher.setAuthTag(authTag);

    let decrypted = decipher.update(encryptedText, 'hex', 'utf8');
    decrypted += decipher.final('utf8');

    if (isObject) {
      try {
        return JSON.parse(decrypted);
      } catch {
        return decrypted;
      }
    }

    return decrypted;
  } catch (err) {
    console.error('Decryption failed for field:', err.message);
    return null;
  }
}

/**
 * Generate deterministic SHA-256 hash for searchable indexing without plaintext exposure
 */
export function hashSearchField(value) {
  if (!value) return null;
  const normalized = String(value).trim().toUpperCase();
  return crypto.createHmac('sha256', getDerivedKey()).update(normalized).digest('hex');
}
